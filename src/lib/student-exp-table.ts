export const REPORT_EXP_VALUES = {
  N: 50,
  R: 500,
  SR: 2000,
  SSR: 10000,
} as const;

export type ReportRarity = keyof typeof REPORT_EXP_VALUES;

export type ReportCounts = Record<ReportRarity, number>;

export type StudentExpCapacityResult = {
  students: number;
  expPerStudent: number;
  totalExp: number;
  leftoverExp: number;
  leftoverReports: ReportCounts;
};

// Smallest first so large reports aren't split across students via pooled EXP.
const REPORT_RARITIES_ASC: ReportRarity[] = ["N", "R", "SR", "SSR"];

export function getExpToReachLevel(level: number): number {
  if (level <= 1) {
    return 0;
  }

  const entry = STUDENT_EXP_TABLE.find((item) => item.level === level);
  return entry?.total ?? 0;
}

export function getExpBetweenLevels(
  fromLevel: number,
  toLevel: number,
): number {
  if (toLevel <= fromLevel) {
    return 0;
  }

  return getExpToReachLevel(toLevel) - getExpToReachLevel(fromLevel);
}

export function reportsToExp(reports: ReportCounts): number {
  return (
    reports.N * REPORT_EXP_VALUES.N +
    reports.R * REPORT_EXP_VALUES.R +
    reports.SR * REPORT_EXP_VALUES.SR +
    reports.SSR * REPORT_EXP_VALUES.SSR
  );
}

// Spend whole reports on a single student (smallest first) until their EXP
// requirement is met. Returns the remaining inventory, or null if the student
// cannot be fully leveled with what's left.
export function tryFundStudent(
  reports: ReportCounts,
  expNeeded: number,
): ReportCounts | null {
  if (expNeeded <= 0) {
    return { ...reports };
  }

  const remaining: ReportCounts = { ...reports };
  let accumulated = 0;

  for (const rarity of REPORT_RARITIES_ASC) {
    const value = REPORT_EXP_VALUES[rarity];

    while (accumulated < expNeeded && remaining[rarity] > 0) {
      remaining[rarity] -= 1;
      accumulated += value;
    }

    if (accumulated >= expNeeded) {
      return remaining;
    }
  }

  return null;
}

export function calculateStudentExpCapacity(
  reports: ReportCounts,
  fromLevel: number,
  toLevel: number,
): StudentExpCapacityResult {
  const expPerStudent = getExpBetweenLevels(fromLevel, toLevel);
  const totalExp = reportsToExp(reports);

  if (expPerStudent <= 0) {
    return {
      students: 0,
      expPerStudent: 0,
      totalExp,
      leftoverExp: totalExp,
      leftoverReports: { ...reports },
    };
  }

  let students = 0;
  let remaining: ReportCounts = { ...reports };

  while (true) {
    const next = tryFundStudent(remaining, expPerStudent);
    if (next === null) {
      break;
    }

    remaining = next;
    students += 1;
  }

  return {
    students,
    expPerStudent,
    totalExp,
    leftoverExp: reportsToExp(remaining),
    leftoverReports: remaining,
  };
}
